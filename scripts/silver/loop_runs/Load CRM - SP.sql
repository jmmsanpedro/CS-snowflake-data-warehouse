USE ROLE ACCOUNTADMIN;
USE DATABASE SALES;

-- Load SILVER.STORES 1 of 2 SILVER CRM tables
-- Load SILVER.CRM_PRD_INFO
CREATE OR REPLACE PROCEDURE SILVER.SP_LOAD_CRM_PRD_INFO_PARAM(V_YEAR INT, V_MONTH INT)
RETURNS STRING
LANGUAGE SQL
AS
BEGIN
    LET SQL_CMD STRING :=
    
    '
    INSERT INTO
        SILVER.CRM_PRD_INFO
    SELECT
        PRD_ID,
        PRD_KEY,
        PRD_NM,
        PRD_PRICE,
        GETDATE()
    FROM
        SALES.BRONZE.CRM_PRD_INFO_EXT
    WHERE
        SRC_YEAR = ' || V_YEAR || ' AND
        SRC_MONTH = ' || V_MONTH ;

    EXECUTE IMMEDIATE SQL_CMD;
    
    RETURN 'Successful Loading of SALES.SIlVER.CRM_PRD_INFO_EXT';
END
;


