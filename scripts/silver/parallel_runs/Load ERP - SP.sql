USE ROLE ACCOUNTADMIN;
USE DATABASE SALES;


-- Load SILVER.STORES 1 of 3 silver tables
CREATE OR REPLACE PROCEDURE SILVER.SP_LOAD_ERP_STORES()
RETURNS STRING
LANGUAGE SQL
AS
BEGIN
    LET V_YEAR INT := (select year FROM METADATADB.PUBLIC.ETL_CONFIG_TABLE WHERE STATUS = 1);
    LET V_MONTH INT:= (select month FROM METADATADB.PUBLIC.ETL_CONFIG_TABLE WHERE STATUS = 1);
    LET SQL_CMD STRING := 
    '
    INSERT INTO 
      SALES.SILVER.ERP_STORES
    SELECT
        *
        EXCLUDE (VALUE, SRC_YEAR, SRC_MONTH, SRC_FILE, SRC_LAST_MODIFIED, SRC_SCAN),
        GETDATE()
    FROM
        SALES.BRONZE.ERP_STORES_EXT
    WHERE
        SRC_YEAR = ' || V_YEAR || ' AND
        SRC_MONTH = ' || V_MONTH;
        
    EXECUTE IMMEDIATE SQL_CMD;

 RETURN 'Successfully loaded SALES.SILVER.ERP_STORES';
END;


